// Generate browser-safe identity data and identical public business records on both sites.
import {readFileSync,writeFileSync,mkdirSync,existsSync} from 'node:fs';
import {dirname} from 'node:path';
import {createHash} from 'node:crypto';
import {E,GC,PMH,personFull,teamFull,brokerageFull,personCompact,teamCompact,brokerageCompact,imageObject,SERVICES,serviceNode} from './entity-lib.mjs';
const evidence=JSON.parse(readFileSync('content/entity/evidence.json','utf8'));
const check=process.argv.includes('--check');
const failures=[];
const contact=evidence.publicContact.values;
for(const key of ['telephone','email','streetAddress','addressLocality','addressRegion','postalCode'])if(contact[key]!==E.nap[key])failures.push(`Contact evidence stale: ${key}`);
if(contact.name!==E.person.name||contact.brokerage!==E.brokerage.name)failures.push('Name or brokerage evidence stale');
const licenses=E.person.credentials.filter(c=>c.category==='license').map(c=>{
 const proof=evidence.licenses.find(p=>p.identifier===c.identifier);
 if(!proof||proof.source!==c.url){failures.push(`License evidence missing or stale: ${c.identifier}`);return null;}
 return {name:c.name,identifier:c.identifier,state:proof.state,url:c.url,statusAsOfCheck:proof.status,checkedOn:proof.checkedOn,expiresOn:proof.expiresOn};
});
if(failures.length)throw Error(failures.join('\n'));
const data={
 ids:E.ids,name:E.person.name,suffix:E.person.honorificSuffix,jobTitle:E.person.jobTitle,
 shortBio:E.person.shortDescription,military:E.person.military,positioning:E.person.positioning,
 brokerage:E.brokerage,telephone:E.nap.telephone,phoneDisplay:E.nap.telephone.replace(/^\+1-(\d{3})-(\d{3})-(\d{4})$/,'($1) $2-$3'),email:E.nap.email,
 contactHours:E.nap.contactHours,businessProfileHours:E.team.openingHoursSpecification,
 address:{streetAddress:E.nap.streetAddress,addressLocality:E.nap.addressLocality,addressRegion:E.nap.addressRegion,postalCode:E.nap.postalCode,addressCountry:'US'},
 addressLine:`${E.nap.streetAddress}, ${E.nap.addressLocality}, ${E.nap.addressRegion} ${E.nap.postalCode}`,
 licenses,areasServed:E.team.areaServed,profiles:E.person.sameAs,
 websites:[{name:'The Costin Team',url:GC+'/',profile:GC+'/team'},{name:'Pensacola Military Housing',url:PMH+'/',profile:PMH+'/about'}],
 contactSource:{url:evidence.publicContact.source,checkedOn:evidence.publicContact.checkedOn},
 recordUrl:GC+'/data/gregg-costin.json',
};
const fingerprint=createHash('sha256').update(JSON.stringify(data)).digest('hex');
const graphs={
 home:{'@context':'https://schema.org','@graph':[
  {'@type':'WebSite','@id':PMH+'/#website',url:PMH+'/',name:'Pensacola Military Housing',publisher:{'@id':E.ids.team},inLanguage:'en-US'},
  imageObject(E.ids.portrait,E.images.portrait),imageObject(E.ids.logo,E.images.logo),
  personFull(),teamFull(),brokerageFull(),...SERVICES.pmh.map(s=>serviceNode('pmh',s)),
 ]},
 compact:{'@context':'https://schema.org','@graph':[personCompact(),teamCompact(),brokerageCompact()]},
};
const publicRecord={recordVersion:1,recordFingerprint:fingerprint,canonicalPersonId:E.ids.person,...data,
 sourceNotes:'License status is recorded as of each checkedOn date. Registry links show current status. Military biography and positioning are supplied by the business owner. This record does not assert an independently audited market ranking.'};
const files={
 'src/entityData.js':'// Generated by scripts/build-identity-record.mjs. Edit content/entity/entity.json and evidence.json.\nexport const IDENTITY = '+JSON.stringify(data,null,2)+';\n',
 'src/entityGraphs.js':'// Generated from the shared entity record. Used for SPA route changes.\nexport const ENTITY_GRAPHS = '+JSON.stringify(graphs)+';\n',
 'public/data/gregg-costin.json':JSON.stringify(publicRecord,null,2)+'\n',
 'civilian-site/data/gregg-costin.json':JSON.stringify(publicRecord,null,2)+'\n',
};
let changed=0;
for(const [file,body] of Object.entries(files)){const old=existsSync(file)?readFileSync(file,'utf8'):'';if(old===body)continue;if(check){failures.push(`Generated identity record stale: ${file}`);continue;}mkdirSync(dirname(file),{recursive:true});writeFileSync(file,body);changed++;}
if(failures.length)throw Error(failures.join('\n'));
console.log(`Identity record ${check?'verified':'generated'}: ${Object.keys(files).length} outputs, ${changed} changed; two official license sources; contact proof matches master.`);
